// Command disco-vectors writes tests/disco_vectors.inc: disco ping and pong
// packets sealed by upstream Tailscale's own disco and types/key packages
// (tailscale.com at commit 9476be94035afa8b896d1e07ee352741b35be7fb, pinned in
// go.mod), and the plaintexts and packets tsppc's side must produce.
//
// Run from the repository root:
//
//	(cd tools/disco-vectors && go run .) > tests/disco_vectors.inc
//
// The module needs the Go toolchain go.mod names (Go's automatic toolchain
// download fetches it). Upstream's Seal uses a random nonce, so regenerating
// rewrites the "UP_" packet bytes by design; tests only open them. DV_SHARED
// comes from x/crypto box.Precompute; the UP_ packets, sealed by upstream's
// DiscoShared, opening under it proves the two agree. The "OUR_" packets use
// a fixed nonce and are deterministic. All keys are made-up test keys.
package main

import (
	"bufio"
	"fmt"
	"net/netip"
	"os"

	"go4.org/mem"
	"golang.org/x/crypto/nacl/box"
	"tailscale.com/disco"
	"tailscale.com/types/key"
)

func pattern(start, step byte) []byte {
	b := make([]byte, 32)
	for i := range b {
		b[i] = start + byte(i)*step
	}
	return b
}

var w = bufio.NewWriter(os.Stdout)

func emit(name string, b []byte) {
	fmt.Fprintf(w, "static const uint8_t %s[%d] = {", name, len(b))
	for i, c := range b {
		if i%12 == 0 {
			fmt.Fprint(w, "\n   ")
		}
		fmt.Fprintf(w, " 0x%02x,", c)
	}
	fmt.Fprint(w, "\n};\n\n")
}

// packet is how magicsock frames a disco message: Magic, sender disco public
// key, then the sealed box (nonce first).
func packet(from key.DiscoPrivate, sealed []byte) []byte {
	pkt := append([]byte(disco.Magic), from.Public().AppendTo(nil)...)
	return append(pkt, sealed...)
}

// fixedSeal is DiscoShared.Seal with a caller-chosen nonce: nonce, then
// box.SealAfterPrecomputation (tag first).
func fixedSeal(fromPriv [32]byte, to key.DiscoPublic, nonce [24]byte, m []byte) []byte {
	pub := to.Raw32()
	var k [32]byte
	box.Precompute(&k, &pub, &fromPriv)
	return box.SealAfterPrecomputation(nonce[:], m, &nonce, &k)
}

func main() {
	// Peer "A" (upstream) and us "B". Made-up keys.
	aRaw := pattern(0x10, 3)
	bRaw := pattern(0x41, 5)
	aRaw[0] &= 248
	aRaw[31] = aRaw[31]&127 | 64
	bRaw[0] &= 248
	bRaw[31] = bRaw[31]&127 | 64
	a := key.DiscoPrivateFromRaw32(mem.B(aRaw))
	b := key.DiscoPrivateFromRaw32(mem.B(bRaw))
	aPub, bPub := a.Public().Raw32(), b.Public().Raw32()

	var bPriv [32]byte
	copy(bPriv[:], bRaw)
	var shared [32]byte
	box.Precompute(&shared, &aPub, &bPriv)

	aNode := key.NodePublicFromRaw32(mem.B(pattern(0x90, 7)))
	bNode := key.NodePublicFromRaw32(mem.B(pattern(0x23, 11)))

	upTx := [12]byte{0xa1, 0xa2, 0xa3, 0xa4, 0xa5, 0xa6, 0xa7, 0xa8, 0xa9, 0xaa, 0xab, 0xac}
	ourTx := [12]byte{0x51, 0x52, 0x53, 0x54, 0x55, 0x56, 0x57, 0x58, 0x59, 0x5a, 0x5b, 0x5c}
	derpSrc := netip.AddrPortFrom(netip.MustParseAddr("127.3.3.40"), 7)
	v6Src := netip.AddrPortFrom(netip.MustParseAddr("fd7a:115c:a1e0::1:2"), 41641)

	upShared := a.Shared(b.Public())
	upPing := packet(a, upShared.Seal((&disco.Ping{TxID: upTx, NodeKey: aNode}).AppendMarshal(nil)))
	upPingPad := packet(a, upShared.Seal((&disco.Ping{TxID: upTx, NodeKey: aNode, Padding: 20}).AppendMarshal(nil)))
	upPingNoKey := packet(a, upShared.Seal((&disco.Ping{TxID: upTx}).AppendMarshal(nil)))
	upPong := packet(a, upShared.Seal((&disco.Pong{TxID: upTx, Src: derpSrc}).AppendMarshal(nil)))
	upPong6 := packet(a, upShared.Seal((&disco.Pong{TxID: upTx, Src: v6Src}).AppendMarshal(nil)))

	// Our side (B to A) with a fixed nonce.
	var nonce [24]byte
	for i := range nonce {
		nonce[i] = 0xc0 + byte(i)
	}
	ourPingPlain := (&disco.Ping{TxID: ourTx, NodeKey: bNode}).AppendMarshal(nil)
	ourPongPlain := (&disco.Pong{TxID: ourTx, Src: derpSrc}).AppendMarshal(nil)
	ourPing := packet(b, fixedSeal(bPriv, a.Public(), nonce, ourPingPlain))
	ourPong := packet(b, fixedSeal(bPriv, a.Public(), nonce, ourPongPlain))

	// Upstream must open what we produce.
	for _, p := range [][]byte{ourPing, ourPong} {
		plain, ok := a.Shared(b.Public()).Open(p[len(disco.Magic)+32:])
		if !ok {
			panic("upstream cannot open our packet")
		}
		if _, err := disco.Parse(plain); err != nil {
			panic(err)
		}
	}

	fmt.Fprint(w, "/* Generated by tools/disco-vectors (upstream tailscale.com@9476be9\n"+
		" * disco and types/key packages). Do not edit. Regenerate with\n"+
		" *   (cd tools/disco-vectors && go run .) > tests/disco_vectors.inc\n"+
		" * A is the upstream peer, B is us. All keys are made-up test keys.\n"+
		" * UP_* packets were sealed by A with upstream's random nonce (so\n"+
		" * regenerating rewrites their bytes by design); OUR_*\n"+
		" * packets are B to A with nonce DV_NONCE. DV_SHARED is x/crypto\n"+
		" * box.Precompute; UP_* (sealed by upstream's DiscoShared) opening under\n"+
		" * it proves the two agree. */\n\n")
	emit("DV_A_PRIV", aRaw)
	emit("DV_A_PUB", aPub[:])
	emit("DV_B_PRIV", bRaw)
	emit("DV_B_PUB", bPub[:])
	emit("DV_SHARED", shared[:])
	emit("DV_A_NODE", aNode.AppendTo(nil))
	emit("DV_B_NODE", bNode.AppendTo(nil))
	emit("DV_UP_TXID", upTx[:])
	emit("DV_OUR_TXID", ourTx[:])
	emit("DV_NONCE", nonce[:])
	v6 := v6Src.Addr().As16()
	emit("DV_V6_SRC_IP", v6[:])
	fmt.Fprintf(w, "#define DV_V6_SRC_PORT %d\n#define DV_DERP_SRC_PORT %d\n\n", v6Src.Port(), derpSrc.Port())
	emit("DV_UP_PING", upPing)
	emit("DV_UP_PING_PAD", upPingPad)
	emit("DV_UP_PING_NOKEY", upPingNoKey)
	emit("DV_UP_PONG", upPong)
	emit("DV_UP_PONG6", upPong6)
	emit("DV_OUR_PING_PLAIN", ourPingPlain)
	emit("DV_OUR_PONG_PLAIN", ourPongPlain)
	emit("DV_OUR_PING", ourPing)
	emit("DV_OUR_PONG", ourPong)
	w.Flush()
}
