#!/usr/bin/env python3
"""Generate the HPACK Huffman decode tables and the test fixture.

Needs the Python `hpack` library (4.x), only to run this script. The outputs
are committed, so building the project never needs Python:

    python3 -I tools/gen_hpack_tables.py src/proto/hpack_huffman.inc tests/hpack_fixture.inc

The Huffman code of RFC 7541 Appendix B is canonical: codes of one length are
consecutive and ascend with the symbol, and each length starts at twice the
end of the previous one. The decoder relies on that, so this script checks it.
"""
import sys
from hpack.huffman_constants import REQUEST_CODES, REQUEST_CODES_LENGTH
from hpack.table import HeaderTable
from hpack.huffman import HuffmanEncoder


def c_str(b):
    return '"' + ''.join('\\x%02x' % c for c in b) + '"'


def main(huff_path, fix_path):
    assert len(REQUEST_CODES) == 257
    order = sorted(range(257), key=lambda s: (REQUEST_CODES_LENGTH[s], s))
    maxlen = max(REQUEST_CODES_LENGTH)
    count = [0] * (maxlen + 1)
    for s in range(257):
        count[REQUEST_CODES_LENGTH[s]] += 1
    # Canonical check.
    code = 0
    idx = 0
    for ln in range(1, maxlen + 1):
        for k in range(count[ln]):
            s = order[idx]
            assert REQUEST_CODES_LENGTH[s] == ln and REQUEST_CODES[s] == code, s
            code += 1
            idx += 1
        code <<= 1

    out = ['/* Generated by tools/gen_hpack_tables.py from RFC 7541 Appendix B. */',
           '/* Number of symbols whose code has each length (index 0 unused). */',
           'static const uint16_t ts_hpack_huff_count[%d] = {' % (maxlen + 1)]
    out.append('    ' + ', '.join(str(c) for c in count))
    out.append('};')
    out.append('/* Symbols ordered by (code length, symbol); 256 is EOS. */')
    out.append('static const uint16_t ts_hpack_huff_sym[257] = {')
    for i in range(0, 257, 12):
        out.append('    ' + ', '.join(str(s) for s in order[i:i + 12]) + ',')
    out.append('};')
    open(huff_path, 'w').write('\n'.join(out) + '\n')

    enc = HuffmanEncoder(REQUEST_CODES, REQUEST_CODES_LENGTH)
    fx = ['/* Generated by tools/gen_hpack_tables.py with the Python hpack library. */',
          '/* Huffman encoding of the one-byte string {b}, for b = 0..255. */',
          'static const struct { uint8_t n; uint8_t b[4]; } fx_huff[256] = {']
    for b in range(256):
        e = enc.encode(bytes([b]))
        assert 1 <= len(e) <= 4
        fx.append('    { %d, { %s } },' % (len(e), ', '.join('0x%02x' % c for c in e + b'\0' * (4 - len(e)))))
    fx.append('};')
    allb = bytes(range(256))
    e = enc.encode(allb)
    fx.append('/* Huffman encoding of the 256-byte string 0x00..0xff. */')
    fx.append('static const uint8_t fx_huff_all[%d] = {' % len(e))
    for i in range(0, len(e), 12):
        fx.append('    ' + ', '.join('0x%02x' % c for c in e[i:i + 12]) + ',')
    fx.append('};')
    st = HeaderTable.STATIC_TABLE
    assert len(st) == 61
    fx.append('/* Static table, indices 1..61. */')
    fx.append('static const struct { const char *n, *v; } fx_static[61] = {')
    for n, v in st:
        fx.append('    { %s, %s },' % (c_str(n), c_str(v)))
    fx.append('};')
    open(fix_path, 'w').write('\n'.join(fx) + '\n')


main(sys.argv[1], sys.argv[2])
